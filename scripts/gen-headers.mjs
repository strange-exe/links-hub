// Writes out/_headers after `next build` (runs as postbuild). Cloudflare Workers static assets apply this file to
// every response: security headers, a strict Content Security Policy, and long-lived caching for hashed assets.
//
// The CSP allows scripts only from this origin plus the exact inline scripts Next.js emitted in this build,
// pinned by SHA-256 hash, so no 'unsafe-inline' / 'unsafe-eval'. Hashes are recomputed on every build.
// Docs: https://developers.cloudflare.com/workers/static-assets/headers/
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("out");
const RESUME_ORIGIN = "https://abhinesh.codes"; // the viewer fetches resume.pdf from the portfolio (CORS *)

async function htmlFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((e) => (e.isDirectory() ? htmlFiles(path.join(dir, e.name)) : e.name.endsWith(".html") ? [path.join(dir, e.name)] : [])),
  );
  return nested.flat();
}

// Inline, executable scripts only: skip src= scripts and JSON data blocks (CSP does not govern those).
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/gi;
const hashes = new Set();
for (const file of await htmlFiles(OUT)) {
  const html = await readFile(file, "utf8");
  for (const [, attrs, body] of html.matchAll(INLINE_SCRIPT)) {
    if (/type=["']application\/(ld\+)?json["']/i.test(attrs) || body.length === 0) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
}

const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(" ")}`,
  "style-src 'self' 'unsafe-inline'", // React style attributes (stagger index, viewer sizes); no script access
  "img-src 'self' data: blob:",
  "font-src 'self'",
  `connect-src 'self' ${RESUME_ORIGIN}`,
  "worker-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

// No Cross-Origin-Opener-Policy: it made WebKit swap processes on navigation and crash in 3/27 viewer test runs
// (27/27 without it, 2026-10-13), and this site opens no popups, so it protected nothing here.
if (csp.length > 1900) throw new Error(`CSP line is ${csp.length} chars; Cloudflare's _headers limit is 2000 per line`);

const headers = `# Generated by scripts/gen-headers.mjs at build time. Do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/pdfjs/*
  Cache-Control: public, max-age=31536000, immutable
`;

await writeFile(path.join(OUT, "_headers"), headers);
console.log(`out/_headers written: ${hashes.size} inline script hashes, CSP ${csp.length} chars`);
